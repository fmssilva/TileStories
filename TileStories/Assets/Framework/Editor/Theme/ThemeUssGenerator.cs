using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;

namespace TileStories.Editor
{
    // Writes a ThemeAsset as the theme stylesheet every UI Toolkit panel reads (_3.3 R12.1): one rule per mode on the app root,
    // .ts-app.ts-theme-<key>.ts-mode-<mode>, holding that mode's values and the shared ones, in the asset's order (deterministic: the same
    // asset always gives the same text). The file is committed -- a build needs it, a diff shows what a theme edit changed -- and
    // ThemeUssStaleTests fails while it differs from what Generate makes of the asset now. Regenerated by the asset's Inspector button.
    public static class ThemeUssGenerator
    {
        public const string GeneratedFolder = "Assets/Framework/Runtime/UI/Theme/Generated";
        private const int NoteWidth = 128;

        private static readonly Regex TokenName = new(@"^--[a-z0-9-]+$");

        // The generated stylesheet's path for a theme
        public static string PathFor(ThemeAsset theme) => GeneratedFolder + "/Theme." + theme.Key + ".uss";

        // The stylesheet text of `theme` (read from `assetPath`, which the header names)
        public static string Generate(ThemeAsset theme, string assetPath)
        {
            if (theme == null) throw new ArgumentNullException(nameof(theme));
            if (theme.Modes.Count == 0) throw new ArgumentException("Theme '" + theme.Key + "' has no mode: nothing to generate");
            var text = new StringBuilder();
            text.Append("/* GENERATED from ").Append(assetPath).Append(" by ThemeUssGenerator -- do not edit by hand: change the asset and\n");
            text.Append("   press Regenerate USS in its Inspector (ThemeUssStaleTests fails while this file is stale).\n");
            text.Append("   The theme's T1 / T2 tokens (_3.3 R12.2) on the app root ThemeController marks; every screen inherits them. */\n");
            foreach (var mode in theme.Modes)
            {
                text.Append('\n').Append(".ts-app.").Append(ThemeController.ThemeClassPrefix).Append(theme.Key)
                    .Append('.').Append(ThemeController.ModeClassPrefix).Append(mode.key).Append(" {\n");
                // - a mode's value wins over a shared one of the same name, as in ThemeResolver: the shared one is left out
                var written = new HashSet<string>();
                AppendSet(text, mode.tokens, written, theme.Key + "/" + mode.key);
                AppendSet(text, theme.Shared, written, theme.Key + "/shared", skip: Names(mode.tokens));
                text.Append("}\n");
            }
            AppendType(text, theme);
            return text.ToString();
        }

        private static readonly Regex OneClass = new(@"^\.[a-z0-9_-]+$");

        // The type roles (_3.3 R12.3), the same in every mode: the two faces as tokens on the marked root -- a USS variable carries a font
        // definition on 6.3 (probed on a real panel, P4.3), so a later knob class can swap a face by overriding one token -- the body face
        // as the root's font (every text of every panel inherits it), the display face on the listed selectors. Nothing is written for a
        // theme with no font library: its panels keep Unity's default font
        private static void AppendType(StringBuilder text, ThemeAsset theme)
        {
            var type = theme.Type;
            if (type == null || type.fontLibrary == null) return;
            string root = ".ts-app." + ThemeController.ThemeClassPrefix + theme.Key;
            text.Append('\n').Append("/* Type: body = ").Append(type.bodyFont).Append(" (bold: ").Append(type.bodyBoldFont)
                .Append(", through its weight table), display = ").Append(type.displayFont).Append(" */\n");
            text.Append(root).Append(" {\n");
            text.Append("    --ts-font-body: ").Append(FontUrl(theme, type.bodyFont)).Append(";\n");
            text.Append("    --ts-font-display: ").Append(FontUrl(theme, type.displayFont)).Append(";\n");
            text.Append("    -unity-font-definition: var(--ts-font-body);\n");
            text.Append("}\n");
            if (type.displaySelectors.Count == 0) return;
            text.Append('\n');
            for (int i = 0; i < type.displaySelectors.Count; i++)
            {
                string selector = type.displaySelectors[i];
                if (selector == null || !OneClass.IsMatch(selector))
                    throw new ArgumentException(theme.Key + "/type: display selector '" + selector + "' is not one class (.lowercase-words)");
                text.Append(root).Append(' ').Append(selector).Append(i < type.displaySelectors.Count - 1 ? ",\n" : " {\n");
            }
            text.Append("    -unity-font-definition: var(--ts-font-display);\n");
            text.Append("}\n");
        }

        // url("/Assets/...") of the UI Toolkit face of `key` -- refused when the key has none (a TMP asset given to UI Toolkit blanks the
        // label silently, R8 S2; a markers-only key cannot be a type role)
        private static string FontUrl(ThemeAsset theme, string key)
        {
            var asset = theme.Type.fontLibrary.GetUiFont(key);
            if (asset == null)
                throw new ArgumentException(theme.Key + "/type: font key '" + key + "' has no UI Toolkit font in " + theme.Type.fontLibrary.name);
            return "url(\"/" + AssetDatabase.GetAssetPath(asset) + "\")";
        }

        // Write the generated stylesheet of `theme` beside the others and import it
        public static string Write(ThemeAsset theme)
        {
            string path = PathFor(theme);
            Directory.CreateDirectory(GeneratedFolder);
            File.WriteAllText(path, Generate(theme, AssetDatabase.GetAssetPath(theme)), new UTF8Encoding(false));
            AssetDatabase.ImportAsset(path);
            Debug.Log("[Theme] " + path + " regenerated from " + AssetDatabase.GetAssetPath(theme));
            return path;
        }

        private static void AppendSet(StringBuilder text, ThemeTokenSet set, HashSet<string> written, string where, HashSet<string> skip = null)
        {
            void Add<T>(List<ThemeToken<T>> tokens, Func<T, string> format)
            {
                foreach (var token in tokens)
                {
                    if (skip != null && skip.Contains(token.name)) continue;
                    if (token.name == null || !TokenName.IsMatch(token.name))
                        throw new ArgumentException(where + ": '" + token.name + "' is not a USS custom property name (--lowercase-words)");
                    if (!written.Add(token.name)) throw new ArgumentException(where + ": " + token.name + " is defined twice");
                    if (!string.IsNullOrWhiteSpace(token.note)) AppendNote(text, token.note);
                    text.Append("    ").Append(token.name).Append(": ").Append(format(token.value)).Append(";\n");
                }
            }
            Add(set.colours, Colour);
            Add(set.lengths, l => Number(l.value) + (l.unit == ThemeLengthUnit.Px ? "px" : "%"));
            Add(set.numbers, Number);
            Add(set.durations, s => Number(s) + "s");
            Add(set.easings, e => Keyword(e.ToString()));
            Add(set.fontStyles, f => Keyword(f.ToString()));
        }

        private static HashSet<string> Names(ThemeTokenSet set) =>
            new(set.colours.Select(t => t.name).Concat(set.lengths.Select(t => t.name)).Concat(set.numbers.Select(t => t.name))
                .Concat(set.durations.Select(t => t.name)).Concat(set.easings.Select(t => t.name)).Concat(set.fontStyles.Select(t => t.name)));

        // rgb() for an opaque colour, rgba() with the alpha as written (round-trip) otherwise -- the shape CardTokens.uss used
        private static string Colour(Color c)
        {
            string rgb = Mathf.RoundToInt(c.r * 255f) + ", " + Mathf.RoundToInt(c.g * 255f) + ", " + Mathf.RoundToInt(c.b * 255f);
            return c.a >= 1f ? "rgb(" + rgb + ")" : "rgba(" + rgb + ", " + Number(c.a) + ")";
        }

        private static string Number(float value) => value.ToString("R", CultureInfo.InvariantCulture);

        // EaseOutCubic -> ease-out-cubic, BoldAndItalic -> bold-and-italic (USS's own keywords)
        private static string Keyword(string enumName) => Regex.Replace(enumName, "(?<!^)([A-Z])", "-$1").ToLowerInvariant();

        // A note as a comment above its token, wrapped to the file's width
        private static void AppendNote(StringBuilder text, string note)
        {
            var line = new StringBuilder("    /* ");
            foreach (string word in Regex.Split(note.Trim(), @"\s+"))
            {
                if (line.Length + word.Length + 1 > NoteWidth && line.Length > 7)
                {
                    text.Append(line.ToString().TrimEnd()).Append('\n');
                    line.Clear().Append("       ");
                }
                line.Append(word).Append(' ');
            }
            text.Append(line.ToString().TrimEnd()).Append(" */\n");
        }
    }
}
